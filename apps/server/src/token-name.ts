/**
 * UIX-400 — как токен получает своё имя.
 *
 * Имён в цепочке три: `characters.name`, `tokenDefinitions.name` и
 * `tokens.name`. Нижнее звено уже производное — имя размещённого токена в
 * снапшоте берётся из определения, а собственное поле только пишется и никогда
 * не читается. Здесь добавляется та же ступень выше: имя определения берётся
 * от персонажа, если своего нет.
 *
 * `NULL` в `tokenDefinitions.name` значит «зовусь как мой персонаж» — это
 * хранимое намерение, а не догадка. Альтернативы отвергнуты планом: безусловная
 * синхронизация затирает намеренные имена, а обновление «только совпавших»
 * пытается восстановить утраченное намерение сравнением строк и ломается тихо.
 *
 * Насколько это не теория: на боевых данных пять определений отличаются именем
 * от своего персонажа, и сломано из них ровно одно («Хорист» у «Могучего
 * Тэйна»). Остальные четыре — осознанные короткие имена вроде «Ллойд» у «Ллойда
 * Олпорта», и безусловная синхронизация снесла бы их все.
 */

/** Имя, которое видит человек. */
export function resolveTokenName(definition: {
  name: string | null;
  characterName?: string | null;
}): string {
  const own = definition.name?.trim();
  if (own) return own;
  const inherited = definition.characterName?.trim();
  if (inherited) return inherited;
  // Персонажа отвязали, а своего имени нет: подпись должна остаться, иначе на
  // карте появится кружок без имени и в списке объектов — пустая строка.
  return "Без имени";
}

/**
 * Следует ли определение за именем персонажа.
 *
 * Отдельно от `resolveTokenName`, потому что интерфейсу нужно показать не
 * только имя, но и то, откуда оно взялось: у палитры это признак «переименуется
 * вместе с персонажем», а у карточки — повод предложить «назвать по персонажу».
 */
export function followsCharacterName(definition: {
  name: string | null;
}): boolean {
  return !definition.name?.trim();
}
