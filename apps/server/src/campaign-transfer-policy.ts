export type CampaignTransferTable=keyof typeof campaignTransferPolicies;
export type CampaignTransferPolicy=typeof campaignTransferPolicies[CampaignTransferTable];
export function campaignTransferCatalog(){
 const tables=Object.values(schema).filter(value=>value instanceof PgTable).map(table=>{const config=getTableConfig(table as PgTable);
 const primaryKey=[...new Set([...config.columns.filter(column=>column.primary).map(column=>column.name),...config.primaryKeys.flatMap(key=>key.columns.map(column=>column.name))])];
 const unique=config.indexes.find(index=>index.config.unique&&!index.config.where&&index.config.columns.every(column=>"name" in column&&typeof column.name==="string"&&config.columns.some(field=>field.name===column.name&&field.notNull)));
 const orderKey=primaryKey.length?primaryKey:unique?.config.columns.map(column=>(column as {name:string}).name)??config.uniqueConstraints.find(constraint=>constraint.columns.every(column=>column.notNull))?.columns.map(column=>column.name)??[];
 return {orderKey,name:config.name,primaryKey,columns:config.columns.map(column=>({name:column.name,sqlType:column.getSQLType(),nullable:!column.notNull})),foreignKeys:config.foreignKeys.map(foreignKey=>{const reference=foreignKey.reference();return {columns:reference.columns.map(column=>column.name),table:getTableConfig(reference.foreignTable).name,target:reference.foreignColumns.map(column=>column.name)};})};}).sort((a,b)=>a.name<b.name?-1:a.name>b.name?1:0);
 const names=tables.map(table=>table.name);if(new Set(names).size!==names.length||names.length!==Object.keys(campaignTransferPolicies).length||names.some(name=>!Object.hasOwn(campaignTransferPolicies,name)))throw Error("CAMPAIGN_TRANSFER_SCHEMA_UNREVIEWED");
 return tables.map(table=>({...table,policy:campaignTransferPolicies[table.name as CampaignTransferTable]}));
}
