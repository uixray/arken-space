/**
 * UIX-468 — семантическое изменение ресурса, а не вычисленное по устаревшему
 * снимку абсолютное значение.
 *
 * Серии кнопок +/- отправляют DELTA: владелец запроса применяет её к самой
 * свежей ревизии персонажа. Восстановление тоже остаётся относительным DELTA,
 * а ручной ввод выражает выбранную пользователем цель и отправляет SET.
 */
export type ResourceCounterIntent =
  | { key: string; kind: "DELTA"; delta: number }
  | { key: string; kind: "SET"; value: number };
