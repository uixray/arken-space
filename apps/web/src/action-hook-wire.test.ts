import { readdirSync, readFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { describe, expect, it } from "vitest";

/**
 * UIX-532 — у каждого хука действий проверен провод, а не только его концы.
 *
 * Порода дефекта, ради которой этот тест написан, встречалась трижды за неделю:
 *
 * * `pinned` (UIX-466) — хук собирал участника очереди вручную, поле за полем,
 *   и одно поле в список не попало. Кнопки ↑/↓ ставили закрепление, сервер его
 *   хранил, оба теста были зелёными — а между ними значение терялось. Снаружи:
 *   «закрепил, а строка уехала», и хуже — каждый бросок стирал закрепление у
 *   всех сразу;
 * * `cursorSendEnabled` (UIX-403) — выключатель курсора не доходил до решения
 *   об отправке. Нашлось диверсией: подмена значения на константу оставляла
 *   весь набор зелёным;
 * * `pinned` во второй раз — уже в другом хуке того же файла.
 *
 * Общее у всех трёх: чистая функция проверена, компонент проверен, **их
 * соединение — нет**. Тело запроса собирается руками, и забытое поле не ломает
 * ни типы, ни один из существующих тестов.
 *
 * Поэтому правило: хук, который собирает тело запроса, обязан иметь тест,
 * проверяющий **отправленное тело**. Не «вызвался ли обработчик» и не «что
 * вернул сервер» — именно то, что ушло в сеть.
 */
const hookDir = fileURLToPath(new URL(".", import.meta.url));
const sourceOf = (file: string) => readFileSync(hookDir + file, "utf8");

/**
 * Долг, а не разрешение. Список существует, потому что правило вводится на
 * живом проекте: восемь хуков написаны до него, и требовать восемь тестов
 * сразу значило бы либо остановить работу, либо выключить проверку в первый же
 * день — ровно то, чего эта проверка должна избежать.
 *
 * Список может только сокращаться: тест ниже роняет прогон, если сюда
 * добавляют новую запись или если запись перестала быть нужной. Пустой список
 * — состояние, к которому идём.
 */
const KNOWN_UNTESTED_HOOKS = new Set([
  "use-access-actions.ts",
  "use-catalog-actions.ts",
  "use-chat-actions.ts",
  "use-player-request-actions.ts",
  "use-stat-layout-actions.ts",
  "use-story-actions.ts",
]);

/**
 * Опасна не отправка как таковая, а **ручная сборка** тела: объект-литерал,
 * перечисляющий поля по одному. Именно оттуда выпал `pinned`.
 *
 * Сквозная передача (`JSON.stringify(transform)`, `body: form`) сюда не
 * попадает намеренно: там нечего забыть — объект уходит целиком, каким пришёл.
 * Требовать тест и от неё значило бы разбавить правило случаями, где дефекта
 * быть не может, и приучить закрывать проверку не глядя.
 */
function assemblesRequestBody(source: string) {
  return /withAction\(\{|JSON\.stringify\(\{/.test(source);
}

const hookFiles = readdirSync(hookDir).filter(
  (file) => /^use-.*actions.*\.ts$/.test(file) && !file.includes(".test."),
);

const testFilesFor = (hook: string) => {
  const base = hook.replace(/\.ts$/, "");
  return readdirSync(hookDir).filter(
    (file) => file.startsWith(`${base}.`) && file.includes(".test."),
  );
};

describe("провод между хуком действий и сервером", () => {
  it("находит сами хуки, иначе проверка молчала бы впустую", () => {
    // Переименование каталога или соглашения об именах не должно превращать
    // эту проверку в тест пустого списка.
    expect(hookFiles.length).toBeGreaterThan(8);
  });

  it("у каждого хука, собирающего тело запроса, есть тест на это тело", () => {
    const missing = hookFiles.filter((hook) => {
      if (!assemblesRequestBody(sourceOf(hook))) return false;
      if (KNOWN_UNTESTED_HOOKS.has(hook)) return false;
      return testFilesFor(hook).length === 0;
    });
    expect(
      missing,
      "хук собирает тело запроса вручную и ничем не проверен: " +
        "забытое поле не сломает ни типы, ни существующие тесты",
    ).toEqual([]);
  });

  it("список долга не пополняется", () => {
    // Добавить сюда запись — значит завести новый долг молча. Пусть это
    // требует правки теста и объяснения в разборе изменений.
    expect(KNOWN_UNTESTED_HOOKS.size).toBeLessThanOrEqual(6);
  });

  it("в списке долга нет записей, которые уже не нужны", () => {
    // Иначе список превратится в кладбище имён: хук получил тест, а строка
    // осталась и продолжает разрешать то, что уже не нарушается.
    const stale = [...KNOWN_UNTESTED_HOOKS].filter(
      (hook) => !hookFiles.includes(hook) || testFilesFor(hook).length > 0,
    );
    expect(stale, "долг закрыт — уберите запись из списка").toEqual([]);
  });
});
