/**
 * UIX-501 — подпись «за кого сделан бросок».
 *
 * Откуда берётся имя и почему его может не быть — в
 * `roll-character-name.ts`; здесь только показ. Запасного текста нет намеренно:
 * отсутствие имени — осмысленный случай, а не сбой, и слово «Персонаж» на этом
 * месте было ровно тем дефектом, из-за которого подпись убирали дважды.
 *
 * Заголовок остаётся читаемым, а не полным: имя усечётся многоточием, если
 * колонка узкая. Это осознанный размен — узкая панель важнее полного имени,
 * и полное имя по-прежнему доступно в подсказке к аватару.
 */
export function RollCharacterName({ name }: { name: string | null }) {
  if (!name) return null;
  return (
    <span className="message-character" title={name}>
      {name}
    </span>
  );
}
