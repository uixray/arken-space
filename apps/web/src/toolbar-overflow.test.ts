import { readFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { describe, expect, it } from "vitest";

/**
 * UIX-503 — кнопка «•••» не существует отдельно от своего содержимого.
 *
 * По снимку экрана игрока меню дополнительных инструментов открывалось пустым.
 * Причина устроена так, что глазами её не видно: содержимое меню было целиком
 * под `role === "GM"`, а сама кнопка — нет. Два решения об одном и том же жили
 * в разных местах, и разошлись они молча.
 *
 * Поведение отдельно проверяется настоящими GM/PLAYER-сеансами в
 * `toolbar-overflow-history.spec.ts`. Эта структурная страховка держит более
 * узкое правило реализации: контейнер кнопки рендерится **вместе** со
 * значением, которое и есть её содержимое, поэтому условие не разъедется снова
 * при следующем добавлении инструмента.
 *
 * Заодно это ловит и обратный дефект: инструмент, добавленный в меню для
 * игрока, но оставленный под чужим условием, — кнопка тогда снова разойдётся
 * с содержимым.
 */
const source = readFileSync(
  fileURLToPath(new URL("./App.tsx", import.meta.url)),
  "utf8",
);

describe("меню дополнительных инструментов карты", () => {
  it("содержимое меню собрано в одно значение", () => {
    // Страховка от собственного разбора: если переменную переименуют, все
    // проверки ниже станут зелёными по пустому множеству.
    expect(source).toContain("const overflowTools =");
  });

  it("кнопка рендерится только при непустом содержимом", () => {
    const control =
      /\{[^{}]*overflowTools[^{}]*&&\s*\(\s*<details className="toolbar-overflow"/;
    expect(
      control.test(source),
      "«•••» рендерится без проверки содержимого — игрок снова откроет пустое меню",
    ).toBe(true);
  });

  it("содержимое подставлено в меню, а не продублировано условием", () => {
    // Если внутри снова появится собственное `role === "GM"`, решение снова
    // окажется в двух местах — ровно та конструкция, из-за которой дефект и был.
    // Закрывающий тег ищется **после** начала меню: в файле есть и другие
    // `<details>`, и поиск с начала дал бы пустой отрезок — то есть зелёную
    // проверку по пустоте.
    const start = source.indexOf('<div className="toolbar-overflow-menu">');
    expect(start, "разметка меню не найдена").toBeGreaterThan(-1);
    const menu = source.slice(start, source.indexOf("</details>", start));
    expect(menu).toContain("{overflowTools}");
    expect(menu).not.toContain('role === "GM"');
  });
});
