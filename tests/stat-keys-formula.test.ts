import { describe, expect, it } from "vitest";
import { rollFormula } from "../apps/server/src/dice";
import { statKeyFromLabel } from "../apps/web/src/stat-keys";

/**
 * UIX-424: ключ характеристики строится на клиенте, а разбирает его серверный
 * движок бросков. Между ними — только договорённость о форме идентификатора, и
 * проверять её копией регулярки в тесте бессмысленно: копия разойдётся с
 * оригиналом ровно тогда, когда это важнее всего.
 *
 * Поэтому здесь ключ прогоняется через **настоящий** `rollFormula`. Если
 * `statKeyFromLabel` когда-нибудь выдаст то, что парсер не примет — упадёт этот
 * тест, а не бросок игрока за столом.
 */
const LABELS = [
  "Сила",
  "Сила воли",
  "Ловкость",
  "Живучесть",
  "Знания",
  "Интеллект",
  "Харизма",
  "Удача",
  "Инициатива",
  "Реакция",
  "Выносливость",
  "Мана",
  "Ближний бой",
  "Дальний бой",
  "Реген Выносливости",
  "Реген Маны",
  "Магия",
  "Торговля",
  "Обман",
  "Запугивание",
  "Внимательность",
  "Меч",
  "Убеждение",
  "Знание подземелий",
];

describe("ключи характеристик принимаются настоящим движком бросков", () => {
  it.each(LABELS)("«%s» годится как имя в формуле", (label) => {
    const key = statKeyFromLabel(label);
    expect(key, `${label} дал пустой ключ`).not.toBe("");

    // Кость минимум двухгранная (движок отвергает 1d1), а `randomInt` здесь
    // всегда возвращает ноль, то есть выпадает единица.
    const result = rollFormula(`1d2+${key}`, { [key]: 7 }, () => 0);
    expect(result.total).toBe(8);
  });

  it("ключ из подписи, начинающейся с цифры, тоже принимается", () => {
    const key = statKeyFromLabel("2-я рука");
    expect(rollFormula(`1d2+${key}`, { [key]: 3 }, () => 0).total).toBe(4);
  });

  it("движок действительно отвергает русское имя — ради чего всё это", () => {
    // Если однажды парсер начнёт принимать кириллицу, транслитерация станет
    // необязательной, и об этом стоит узнать отсюда, а не догадаться.
    expect(() => rollFormula("1d2+Сила", { Сила: 7 }, () => 0)).toThrow();
  });
});
