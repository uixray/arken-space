/**
 * UIX-521: решение о том, что считать дефектом, и сборка читаемого сообщения.
 *
 * Вынесено из стража отдельным модулем по одной причине: это чистые функции,
 * и проверять их браузерным прогоном значило бы тратить двадцать минут на то,
 * что проверяется за миллисекунду. Тесты — `tests/react-console-guard.test.ts`.
 */

/**
 * Сообщения React, каждое из которых означает дефект, а не стиль.
 *
 * Список намеренно узкий: ронять прогон на любой строке из консоли нельзя —
 * там 401 на `/api/bootstrap` до входа, 404 на favicon и недоступный CDN
 * шрифтов. Такая проверка стала бы шумом, который отключат при первом же
 * красном прогоне.
 */
export const REACT_DEFECTS = [
  "Cannot update a component",
  "Maximum update depth exceeded",
] as const;

export function isReactDefect(text: string): boolean {
  return REACT_DEFECTS.some((pattern) => text.includes(pattern));
}

/**
 * Подставляет аргументы консоли на места `%s`.
 *
 * React отдаёт формат и подстановки по отдельности, а `ConsoleMessage.text()`
 * склеивает их встык — имена компонентов оказываются хвостом за ссылкой на
 * документацию, и читающий красный прогон ищет, какой компонент чей.
 *
 * Аргументы берутся у Playwright, а не вычисляются из текста. Первая версия
 * этого модуля отрезала хвост по числу `%s` и на сообщении, где подстановок
 * меньше, чем слов в конце, съедала кусок самого текста. Поймал юнит-тест;
 * угадывание убрано вместе с ошибкой.
 */
export function formatReactConsoleMessage(
  format: string,
  args: readonly string[],
): string {
  let index = 0;
  return format.replace(/%s/g, () =>
    index < args.length ? args[index++]! : "%s",
  );
}
