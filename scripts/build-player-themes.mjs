import { readFile, writeFile } from "node:fs/promises";
import { format, resolveConfig } from "prettier";

const source = "tokens/player-themes/player-themes.tokens.json";
const cssOutput = "apps/web/src/design-system/player-themes.generated.css";
const registryOutput = "apps/web/src/design-system/player-themes.generated.ts";
const allowedVariables = new Set([
  "color-accent",
  "color-text-accent",
  "color-surface-selected",
  "color-canvas",
  "color-surface",
  "color-surface-raised",
  "color-border",
  "color-text",
  "color-text-muted",
  "color-text-faint",
  "color-danger",
  "color-danger-ink",
  "color-danger-surface",
  "color-shadow",
  "color-control-border",
  "color-focus",
  "color-accent-ink",
  "color-overlay",
  "color-surface-hover",
  "color-surface-active",
  "color-accent-hover",
  "color-accent-active",
  "button-primary-background",
  "button-primary-ink",
  "field-background",
  "field-border",
  "field-ink",
  "state-error-ink",
  "focus-color",
]);
const hexColor = /^#[0-9a-f]{6}$/i;
const rgbaColor =
  /^rgba\((\d{1,3}), (\d{1,3}), (\d{1,3}), (0|1|0\.\d+|1\.0+)\)$/i;

function isSourceColor(value) {
  if (hexColor.test(value)) return true;
  const match = rgbaColor.exec(value);
  return Boolean(
    match &&
    [match[1], match[2], match[3]].every((channel) => Number(channel) <= 255) &&
    Number(match[4]) >= 0 &&
    Number(match[4]) <= 1,
  );
}

const document = JSON.parse(await readFile(source, "utf8"));
const themes = document?.themes;
if (!themes || typeof themes !== "object" || Array.isArray(themes)) {
  throw new Error(`${source} must contain a themes object.`);
}
const themeIds = Object.keys(themes);
if (
  themeIds.length === 0 ||
  themeIds.some((id) => !/^[a-z][a-z0-9-]*$/.test(id))
) {
  throw new Error(
    `${source} theme ids must be non-empty safe CSS identifiers.`,
  );
}

const metadata = themeIds.map((id) => {
  const theme = themes[id];
  if (
    !theme ||
    typeof theme.name !== "string" ||
    !theme.name.trim() ||
    !["dark", "light"].includes(theme.colorScheme) ||
    !Number.isInteger(theme.version) ||
    theme.version < 1 ||
    !theme.tokens ||
    typeof theme.tokens !== "object" ||
    Array.isArray(theme.tokens)
  ) {
    throw new Error(
      `${id} must be complete configuration, not runtime metadata.`,
    );
  }
  const names = Object.keys(theme.tokens);
  if (
    names.length !== allowedVariables.size ||
    names.some((name) => !allowedVariables.has(name)) ||
    [...allowedVariables].some((name) => !Object.hasOwn(theme.tokens, name))
  ) {
    throw new Error(
      `${id} must have exactly the canonical personal-theme token keys.`,
    );
  }
  for (const name of names) {
    const token = theme.tokens[name];
    if (
      token?.$type !== "color" ||
      typeof token.$value !== "string" ||
      !isSourceColor(token.$value)
    ) {
      throw new Error(
        `${id}.${name} must be an injection-safe resolved source color token.`,
      );
    }
  }
  return {
    id,
    name: theme.name,
    colorScheme: theme.colorScheme,
    version: theme.version,
  };
});

const declarations = metadata.map(({ id, colorScheme }) => {
  const lines = Object.entries(themes[id].tokens).map(
    ([name, token]) => `  --${name}: ${token.$value};`,
  );
  return `html[data-player-theme="${id}"] {\n  color-scheme: ${colorScheme};\n${lines.join("\n")}\n}`;
});

await Promise.all([
  writeFile(
    cssOutput,
    await format(
      `/**\n * Do not edit directly. Generated by scripts/build-player-themes.mjs\n * from tokens/player-themes/player-themes.tokens.json.\n */\n\n${declarations.join("\n\n")}\n`,
      { ...(await resolveConfig(cssOutput)), filepath: cssOutput },
    ),
  ),
  writeFile(
    registryOutput,
    await format(
      `/** Do not edit directly. Generated by scripts/build-player-themes.mjs. */\nexport const PLAYER_THEME_DEFINITIONS = ${JSON.stringify(metadata, null, 2)} as const;\n`,
      { ...(await resolveConfig(registryOutput)), filepath: registryOutput },
    ),
  ),
]);
